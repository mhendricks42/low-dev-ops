// Generates TypeScript model types from the backend JSON Schemas (never hand-written).
// `node scripts/types.mjs` writes them; `--check` fails if the committed files drift.
import { readFile, writeFile } from 'node:fs/promises'
import { compileFromFile } from 'json-schema-to-typescript'

const targets = [
  ['../backend/schema/project.schema.json', 'src/model/project.ts'],
  ['../catalog/catalog.schema.json', 'src/model/catalog-entry.ts'],
]
const check = process.argv.includes('--check')
let drift = false
for (const [schema, out] of targets) {
  const ts = await compileFromFile(schema, {
    bannerComment: '// Generated by scripts/types.mjs from ' + schema + '. Do not edit.',
    additionalProperties: false,
    style: { semi: false, singleQuote: true, printWidth: 100 },
  })
  if (check) {
    const current = await readFile(out, 'utf8').catch(() => '')
    if (current !== ts) {
      console.error(`${out} is out of date: run npm run types`)
      drift = true
    }
  } else {
    await writeFile(out, ts)
  }
}
process.exit(drift ? 1 : 0)
