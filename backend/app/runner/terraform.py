"""Terraform plan and apply for one project, as the signed-in user (M5).

Plan: regenerate main.tf from project.json, write runtime.tf, init, plan, show -json, guardrails,
then keep a plan record. Apply: only the saved plan.tfplan, only when every gate holds, and at
most once. Runs work in the project dir through its O_NOFOLLOW dir fd (see app/api/projects.py).
"""

import hashlib
import json
import os
import threading
from collections.abc import Callable
from contextlib import suppress
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from fastapi import HTTPException

from app import azure, proc, settings
from app.api.catalog import CATALOG
from app.api.projects import _open_project_dir, _read_project, _write_atomic
from app.guardrails.run import Report, check
from app.hcl.generate import generate
from app.runner.runs import REGISTRY, Run, RunBusy, Step, run_steps

INIT_TIMEOUT = 10 * 60
PLAN_TIMEOUT = 30 * 60
SHOW_TIMEOUT = 5 * 60
APPLY_TIMEOUT = 60 * 60
PLAN_FILE = "plan.tfplan"
NO_PLAN = "Plan again: there is no reviewed plan"
# Kept out of main.tf so the M1 snapshots and the HCL editor never see it. AVM modules need
# `features`; state is read with Entra ID, never with storage keys.
RUNTIME_TF = """\
# Generated by LowDevOps for every run. Do not edit.
terraform {
  backend "azurerm" {}
}

provider "azurerm" {
  features {}
  storage_use_azuread = true
}
"""


@dataclass(frozen=True)
class Change:
    address: str
    action: str  # create, update, delete or replace


@dataclass(frozen=True)
class Summary:
    changes: list[Change] = field(default_factory=list)  # in plan order, no-ops left out

    def count(self, action: str) -> int:
        return sum(1 for c in self.changes if c.action == action)

    @property
    def destroys(self) -> list[str]:
        return [c.address for c in self.changes if c.action in ("delete", "replace")]

    def text(self) -> str:
        replace = self.count("replace")
        return (
            f"{self.count('create') + replace} to add, {self.count('update')} to change, "
            f"{self.count('delete') + replace} to destroy"
        )


@dataclass(frozen=True)
class PlanRecord:
    plan_sha256: str
    model_sha256: str
    subscription_id: str
    created_at: str
    summary: Summary
    report: Report


# The plan waiting for apply, by project. In memory on purpose: after a restart, plan again.
_PLANS: dict[str, PlanRecord] = {}
_PLANS_LOCK = threading.Lock()


def key(name: str) -> str:
    return f"project:{name}"


def plan_record(name: str) -> PlanRecord | None:
    with _PLANS_LOCK:
        return _PLANS.get(name)


def summarize(plan: dict[str, Any]) -> Summary:
    changes: list[Change] = []
    for change in plan.get("resource_changes") or []:
        if not isinstance(change, dict) or change.get("mode") != "managed":
            continue
        actions = set((change.get("change") or {}).get("actions") or [])
        if {"create", "delete"} <= actions:
            action = "replace"
        elif len(actions) == 1 and actions <= {"create", "update", "delete"}:
            action = actions.pop()
        else:
            continue  # no-op, read
        changes.append(Change(address=str(change.get("address")), action=action))
    return Summary(changes)


def terraform_env(subscription_id: str) -> dict[str, str]:
    # Only the signed-in az user and the confirmed subscription. Every inherited TF_* and ARM_*
    # is dropped (TF_CLI_ARGS_* could add -var or -backend-config, TF_WORKSPACE another state,
    # ARM_ENVIRONMENT another cloud): terraform sees exactly the settings below.
    return proc.inherited_env(
        drop_prefixes=(*azure.CREDENTIAL_PREFIXES, "TF_", "ARM_"),
        extra={
            "ARM_USE_CLI": "true",
            "ARM_SUBSCRIPTION_ID": subscription_id,
            "TF_IN_AUTOMATION": "1",
            "TF_INPUT": "0",
        },
    )


def _sha256_at(dir_fd: int, filename: str) -> str | None:
    try:
        fd = os.open(filename, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=dir_fd)
    except FileNotFoundError:
        return None
    digest = hashlib.sha256()
    try:
        while chunk := os.read(fd, 1 << 20):
            digest.update(chunk)
    finally:
        os.close(fd)
    return digest.hexdigest()


def _open_log(run: Run, dir_fd: int) -> None:
    # A fresh file each run: whatever is at run.log (a hard link to another file, a FIFO) is
    # unlinked, never written through or waited on.
    with suppress(FileNotFoundError):
        os.unlink("run.log", dir_fd=dir_fd)
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW
    run.log_to(os.open("run.log", flags, 0o600, dir_fd=dir_fd))


def _cwd(dir_fd: int) -> Path:
    # The child chdirs through the fd we hold, so it lands in the dir we checked.
    return Path(f"/proc/self/fd/{dir_fd}")


def _start(name: str, kind: str, work: Callable[[Run], int]) -> Run:
    try:
        return REGISTRY.start(key(name), kind, work)
    except RunBusy as e:
        raise HTTPException(409, detail={"message": str(e), "runId": e.run.id}) from e


def start_plan(name: str, subscription_id: str) -> Run:
    sub = subscription_id.lower()
    with _open_project_dir(name, create=False) as dir_fd:
        project, _ = _read_project(dir_fd, name)
    # The subscription-confirm step: the user confirmed the exact id the project targets.
    if project.subscription.id.lower() != sub:
        raise HTTPException(
            422, detail={"message": "confirm the project's subscription id to plan"}
        )
    try:
        azure.az(["account", "show", "--subscription", sub])
    except azure.NotLoggedIn as e:
        raise HTTPException(409, detail={"message": "Sign in with az login first"}) from e
    except azure.AzError as e:
        raise HTTPException(
            409, detail={"message": f"Your az login cannot use subscription {sub}: {e}"}
        ) from e
    backend = settings.load().backends.get(sub)
    if backend is None:
        raise HTTPException(409, detail={"message": "Bootstrap the state backend first"})

    def work(run: Run) -> int:
        with _open_project_dir(name, create=False) as dir_fd:
            _open_log(run, dir_fd)
            with _PLANS_LOCK:  # a new plan replaces the old one, reviewed or not
                _PLANS.pop(name, None)
            with suppress(FileNotFoundError):
                os.unlink(PLAN_FILE, dir_fd=dir_fd)
            # project.json is the only source of truth: re-read it, and hash what is planned.
            project, model = _read_project(dir_fd, name)
            if project.subscription.id.lower() != sub:
                run.append("Error: the project's subscription changed; confirm it again")
                return 1
            _write_atomic(dir_fd, "main.tf", generate(project))
            _write_atomic(dir_fd, "runtime.tf", RUNTIME_TF)
            cwd, env = _cwd(dir_fd), terraform_env(sub)
            backend_config = {
                "resource_group_name": backend.resource_group,
                "storage_account_name": backend.storage_account,
                "container_name": backend.container,
                "key": f"{name}.tfstate",
                "use_azuread_auth": "true",
                "subscription_id": sub,
            }
            init = ["terraform", "init", "-input=false", "-no-color", "-reconfigure"]
            init += [f"-backend-config={k}={v}" for k, v in backend_config.items()]
            plan = ["terraform", "plan", "-input=false", "-no-color", f"-out={PLAN_FILE}"]
            code = run_steps(
                run, [Step(init, cwd, INIT_TIMEOUT, env), Step(plan, cwd, PLAN_TIMEOUT, env)]
            )
            if code != 0:
                return code
            run.append(f"$ terraform show -json {PLAN_FILE}")
            show = ["terraform", "show", "-no-color", "-json", PLAN_FILE]
            done = proc.run(show, cwd=cwd, timeout=SHOW_TIMEOUT, env=env)
            if done.returncode != 0:
                run.append(done.stderr.strip() or f"terraform show failed ({done.returncode})")
                return done.returncode
            plan_json = json.loads(done.stdout)
            run.append("Running guardrails on the plan…")
            report = check(project, CATALOG, plan_json)
            plan_sha = _sha256_at(dir_fd, PLAN_FILE)
            if plan_sha is None:
                run.append(f"Error: terraform wrote no {PLAN_FILE}")
                return 1
            summary = summarize(plan_json)
            record = PlanRecord(
                plan_sha256=plan_sha,
                model_sha256=hashlib.sha256(model).hexdigest(),
                subscription_id=sub,
                created_at=datetime.now(UTC).isoformat(timespec="seconds"),
                summary=summary,
                report=report,
            )
            with _PLANS_LOCK:
                _PLANS[name] = record
            run.append(f"Plan ready: {summary.text()}.")
            if not report.apply_allowed:
                run.append("Guardrails block apply: see the findings.")
            return 0

    return _start(name, "plan", work)


def _stale(dir_fd: int, name: str, record: PlanRecord) -> str | None:
    """Why the saved plan may not be applied any more, or None."""
    if _sha256_at(dir_fd, PLAN_FILE) != record.plan_sha256:
        return NO_PLAN
    _, model = _read_project(dir_fd, name)
    if hashlib.sha256(model).hexdigest() != record.model_sha256:
        return "The project changed since the plan. Plan again."
    return None


def start_apply(name: str, plan_sha256: str, confirm_name: str, confirm_destroy: bool) -> Run:
    active = REGISTRY.current(key(name))
    if active is not None and active.status == "running":  # say which run, as a plan does
        raise HTTPException(409, detail={"message": str(RunBusy(active)), "runId": active.id})
    record = plan_record(name)
    if record is None or record.plan_sha256 != plan_sha256:
        raise HTTPException(409, detail={"message": NO_PLAN})
    with _open_project_dir(name, create=False) as dir_fd:
        reason = _stale(dir_fd, name, record)
    if reason is not None:
        raise HTTPException(409, detail={"message": reason})
    if confirm_name != name:
        raise HTTPException(422, detail={"message": "type the project name to apply"})
    if record.summary.destroys and not confirm_destroy:
        raise HTTPException(
            422,
            detail={
                "message": f"confirm that this destroys or replaces "
                f"{len(record.summary.destroys)} resources"
            },
        )
    if not record.report.apply_allowed:
        blocking = [f.id for f in record.report.findings if not f.waivable]
        raise HTTPException(
            409,
            detail={
                "message": "Guardrails block apply"
                if record.report.plan_scanned
                else "The plan was not scanned",
                "findings": blocking,
            },
        )

    def work(run: Run) -> int:
        with _open_project_dir(name, create=False) as dir_fd:
            _open_log(run, dir_fd)
            # Single use, and re-checked now that this run holds the project: nothing can have
            # been planned or saved between the checks above and here without being caught.
            with _PLANS_LOCK:
                current = _PLANS.pop(name, None)
            if current is not record or _stale(dir_fd, name, record) is not None:
                run.append(f"Error: {NO_PLAN}")
                return 1
            try:
                apply = ["terraform", "apply", "-input=false", "-no-color", PLAN_FILE]
                step = Step(
                    apply, _cwd(dir_fd), APPLY_TIMEOUT, terraform_env(record.subscription_id)
                )
                return run_steps(run, [step])
            finally:
                with suppress(FileNotFoundError):
                    os.unlink(PLAN_FILE, dir_fd=dir_fd)

    return _start(name, "apply", work)
